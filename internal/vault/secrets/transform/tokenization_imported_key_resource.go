// TransformTokenizationImportedKeyResource manages a Vault Transform tokenization
// transformation whose key material was imported (BYOK) instead of generated by Vault. The
// resource combines the initial import (/transformations/tokenization/:name/import) with the
// ongoing transformation settings (/transformations/tokenization/:name) and the key settings
// (/tokenization/keys/:name/config).
type TransformTokenizationImportedKeyResource struct {
	base.ResourceWithConfigure
}

// TransformTokenizationImportedKeyModel describes the Terraform resource data model.
type TransformTokenizationImportedKeyModel struct {
	ImportedKeyCommonModel

	AllowRotation types.Bool   `tfsdk:"allow_rotation"`
	MappingMode   types.String `tfsdk:"mapping_mode"`
	MaxTTL        types.Int64  `tfsdk:"max_ttl"`
	Stores        types.List   `tfsdk:"stores"`

	// Key settings (/tokenization/keys/:name and /config).
	MinDecryptionVersion types.Int64 `tfsdk:"min_decryption_version"`
	AutoRotatePeriod     types.Int64 `tfsdk:"auto_rotate_period"`
	LatestVersion        types.Int64 `tfsdk:"latest_version"`
	MinAvailableVersion  types.Int64 `tfsdk:"min_available_version"`
}

func (r *TransformTokenizationImportedKeyResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_transform_transformation_tokenization_imported_key"
}

