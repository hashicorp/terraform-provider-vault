func (r *TransformTokenizationImportedKeyResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan TransformTokenizationImportedKeyModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// ciphertext_wo is write-only, so it is only available from config.
	var config TransformTokenizationImportedKeyModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &config)...)
	if resp.Diagnostics.HasError() {
		return
	}

	cli, err := client.GetClient(ctx, r.Meta(), plan.Namespace.ValueString())
	if err != nil {
		resp.Diagnostics.AddError(errutil.ClientConfigureErr(err))
		return
	}

	if !provider.IsEnterpriseSupported(r.Meta()) {
		resp.Diagnostics.AddError("Unsupported Vault edition", "The Transform secrets engine requires Vault Enterprise.")
		return
	}

	body, d := plan.importBody(ctx, &config.ImportedKeyCommonModel)
	resp.Diagnostics.Append(d...)
	resp.Diagnostics.Append(plan.addTokenizationSettings(ctx, body)...)
	if resp.Diagnostics.HasError() {
		return
	}
	// allow_rotation is only accepted by /import, so it is not part of the shared settings.
	if !plan.AllowRotation.IsNull() && !plan.AllowRotation.IsUnknown() {
		body["allow_rotation"] = plan.AllowRotation.ValueBool()
	}

	mount := plan.Mount.ValueString()
	name := plan.Name.ValueString()

	if _, err := cli.Logical().WriteWithContext(ctx, importPath(mount, typeTokenization, name), body); err != nil {
		resp.Diagnostics.AddError(errutil.VaultCreateErr(err))
		return
	}

	// deletion_allowed is not accepted by /import, only by the update endpoint, so it is applied
	// with a second write.
	//
	// The transformation exists in Vault once /import succeeds. Record errors from the follow-up
	// writes, then read and save the actual state if possible so the transformation stays tracked.
	if !plan.DeletionAllowed.IsNull() && !plan.DeletionAllowed.IsUnknown() {
		b := map[string]any{"deletion_allowed": plan.DeletionAllowed.ValueBool()}
		if _, err := cli.Logical().WriteWithContext(ctx, typedPath(mount, typeTokenization, name), b); err != nil {
			resp.Diagnostics.AddError(errutil.VaultCreateErr(err))
		}
	}
	if keyBody := plan.keyConfigBody(); len(keyBody) > 0 {
		if _, err := cli.Logical().WriteWithContext(ctx, keyConfigPath(mount, name), keyBody); err != nil {
			resp.Diagnostics.AddError(errutil.VaultCreateErr(err))
		}
	}

	found, d := r.readFromVault(ctx, cli, &plan)
	resp.Diagnostics.Append(d...)
	if d.HasError() {
		return
	}
	if !found {
		resp.Diagnostics.AddError(errutil.VaultReadResponseNil())
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *TransformTokenizationImportedKeyResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state TransformTokenizationImportedKeyModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	cli, err := client.GetClient(ctx, r.Meta(), state.Namespace.ValueString())
	if err != nil {
		resp.Diagnostics.AddError(errutil.ClientConfigureErr(err))
		return
	}

	found, d := r.readFromVault(ctx, cli, &state)
	resp.Diagnostics.Append(d...)
	if resp.Diagnostics.HasError() {
		return
	}

	if !found {
		tflog.Warn(ctx, "Transform transformation not found, removing from state")
		resp.State.RemoveResource(ctx)
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *TransformTokenizationImportedKeyResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan TransformTokenizationImportedKeyModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	var state TransformTokenizationImportedKeyModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// ciphertext_wo is write-only, so it is only available from config.
	var config TransformTokenizationImportedKeyModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &config)...)
	if resp.Diagnostics.HasError() {
		return
	}

	cli, err := client.GetClient(ctx, r.Meta(), plan.Namespace.ValueString())
	if err != nil {
		resp.Diagnostics.AddError(errutil.ClientConfigureErr(err))
		return
	}

	mount := plan.Mount.ValueString()
	name := plan.Name.ValueString()

	// Only a changed ciphertext_wo_version imports a new key version. ciphertext_wo is
	// write-only, so its value comes from config.
	importNewVersion := !plan.CiphertextWOVersion.IsNull() && !plan.CiphertextWOVersion.Equal(state.CiphertextWOVersion)
	if importNewVersion {
		importBody := map[string]any{}
		if !config.CiphertextWO.IsNull() && !config.CiphertextWO.IsUnknown() {
			importBody["ciphertext"] = config.CiphertextWO.ValueString()
		}
		if !plan.HashFunction.IsNull() && !plan.HashFunction.IsUnknown() {
			importBody["hash_function"] = plan.HashFunction.ValueString()
		}
		if _, err := cli.Logical().WriteWithContext(ctx, importVersionPath(mount, typeTokenization, name), importBody); err != nil {
			resp.Diagnostics.AddError(errutil.VaultUpdateErr(err))
			return
		}
	}

	// update params shared by both transformation types
	body, d := plan.updateBody(ctx)
	resp.Diagnostics.Append(d...)
	// update params specific to tokenization transformations
	resp.Diagnostics.Append(plan.addTokenizationSettings(ctx, body)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Record errors from the writes below instead of returning early.
	if len(body) > 0 {
		if _, err := cli.Logical().WriteWithContext(ctx, typedPath(mount, typeTokenization, name), body); err != nil {
			resp.Diagnostics.AddError(errutil.VaultUpdateErr(err))
		}
	}
	if keyBody := plan.keyConfigBody(); len(keyBody) > 0 {
		if _, err := cli.Logical().WriteWithContext(ctx, keyConfigPath(mount, name), keyBody); err != nil {
			resp.Diagnostics.AddError(errutil.VaultUpdateErr(err))
		}
	}
	if resp.Diagnostics.HasError() && !importNewVersion {
		// Nothing irreversible was written, so return here since there is no new state to save.
		return
	}

	// Otherwise /import_version succeeded and the new key version exists in Vault.
	// The prior state is stale, so even though the transformation update or key config write failed,
	// continue on to read and save the current state.
	// Otherwise the next apply would import the same key material again as a duplicate version.
	found, d := r.readFromVault(ctx, cli, &plan)
	resp.Diagnostics.Append(d...)
	if d.HasError() {
		return
	}
	if !found {
		resp.Diagnostics.AddError(errutil.VaultReadResponseNil())
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *TransformTokenizationImportedKeyResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state TransformTokenizationImportedKeyModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	cli, err := client.GetClient(ctx, r.Meta(), state.Namespace.ValueString())
	if err != nil {
		resp.Diagnostics.AddError(errutil.ClientConfigureErr(err))
		return
	}

	p := typedPath(state.Mount.ValueString(), typeTokenization, state.Name.ValueString())
	if _, err := cli.Logical().DeleteWithContext(ctx, p); err != nil {
		resp.Diagnostics.AddError(errutil.VaultDeleteErr(err))
		return
	}
}

func (r *TransformTokenizationImportedKeyResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	common, err := importedKeyFromID(req.ID)
	if err != nil {
		resp.Diagnostics.AddError("Invalid import ID", err.Error())
		return
	}
	data := TransformTokenizationImportedKeyModel{ImportedKeyCommonModel: common}

	if !provider.IsEnterpriseSupported(r.Meta()) {
		resp.Diagnostics.AddError("Unsupported Vault edition", "The Transform secrets engine requires Vault Enterprise.")
		return
	}

	cli, err := client.GetClient(ctx, r.Meta(), data.Namespace.ValueString())
	if err != nil {
		resp.Diagnostics.AddError(errutil.ClientConfigureErr(err))
		return
	}

	found, d := r.readFromVault(ctx, cli, &data)
	resp.Diagnostics.Append(d...)
	if resp.Diagnostics.HasError() {
		return
	}

	if !found {
		resp.Diagnostics.AddError("Resource not found", fmt.Sprintf("Transform transformation %q not found on mount %q", data.Name.ValueString(), data.Mount.ValueString()))
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

// readFromVault populates data from Vault. It returns false if the transformation does
// not exist (or on error, in which case the returned diag.Diagnostics contains the error).
// allow_rotation is not returned by Vault, so it keeps its planned or prior value.
func (r *TransformTokenizationImportedKeyResource) readFromVault(ctx context.Context, cli *vaultclient.Client, data *TransformTokenizationImportedKeyModel) (bool, diag.Diagnostics) {
	mount := data.Mount.ValueString()
	name := data.Name.ValueString()

	secretData, diags := readTransformation(ctx, cli, mount, name, typeTokenization)
	if diags.HasError() || secretData == nil {
		return false, diags
	}
	diags.Append(data.setFromVault(ctx, secretData)...)

	data.MappingMode = util.StringValueOrNull(secretData[consts.FieldMappingMode])
	data.MaxTTL = util.Int64ValueOrNull(secretData[consts.FieldMaxTTL])
	if raw, ok := secretData[consts.FieldStores]; ok && raw != nil {
		stores, d := types.ListValueFrom(ctx, types.StringType, raw)
		diags.Append(d...)
		if !d.HasError() {
			data.Stores = stores
		}
	} else if data.Stores.IsUnknown() {
		data.Stores = types.ListNull(types.StringType)
	}

	keySecret, err := cli.Logical().ReadWithContext(ctx, tokenizationKeyPath(mount, name))
	if err != nil {
		diags.AddError(errutil.VaultReadErr(err))
		return false, diags
	}
	var keyData map[string]any
	if keySecret != nil {
		keyData = keySecret.Data
	}
	data.LatestVersion = util.Int64ValueOrNull(keyData[consts.FieldLatestVersion])
	data.MinAvailableVersion = util.Int64ValueOrNull(keyData[consts.FieldMinAvailableVersion])
	data.MinDecryptionVersion = util.Int64ValueOrNull(keyData[consts.FieldMinDecryptionVersion])
	data.AutoRotatePeriod = util.Int64ValueOrNull(keyData[consts.FieldAutoRotatePeriod])

	return true, diags
}

// addTokenizationSettings adds the tokenization-specific settings of the transformation to the
// create (/import) and update request bodies, on top of the part shared with FPE transformations.
func (m *TransformTokenizationImportedKeyModel) addTokenizationSettings(ctx context.Context, body map[string]any) diag.Diagnostics {
	var diags diag.Diagnostics
	if !m.MappingMode.IsNull() && !m.MappingMode.IsUnknown() {
		body["mapping_mode"] = m.MappingMode.ValueString()
	}
	if !m.MaxTTL.IsNull() && !m.MaxTTL.IsUnknown() {
		body["max_ttl"] = m.MaxTTL.ValueInt64()
	}
	if !m.Stores.IsNull() && !m.Stores.IsUnknown() {
		stores := make([]string, 0, len(m.Stores.Elements()))
		diags.Append(m.Stores.ElementsAs(ctx, &stores, false)...)
		if !diags.HasError() {
			body["stores"] = stores
		}
	}
	return diags
}

// keyConfigBody builds the /tokenization/keys/:name/config request body from the plan.
func (m *TransformTokenizationImportedKeyModel) keyConfigBody() map[string]any {
	body := map[string]any{}
	if !m.MinDecryptionVersion.IsNull() && !m.MinDecryptionVersion.IsUnknown() {
		body["min_decryption_version"] = m.MinDecryptionVersion.ValueInt64()
	}
	if !m.AutoRotatePeriod.IsNull() && !m.AutoRotatePeriod.IsUnknown() {
		body["auto_rotate_period"] = m.AutoRotatePeriod.ValueInt64()
	}
	return body
}
