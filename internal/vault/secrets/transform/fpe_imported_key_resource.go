func (r *TransformFPEImportedKeyResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	common, err := importedKeyFromID(req.ID)
	if err != nil {
		resp.Diagnostics.AddError("Invalid import ID", err.Error())
		return
	}
	data := TransformFPEImportedKeyModel{ImportedKeyCommonModel: common}

	if !provider.IsEnterpriseSupported(r.Meta()) {
		resp.Diagnostics.AddError("Unsupported Vault edition", "The Transform secrets engine requires Vault Enterprise.")
		return
	}

	cli, err := client.GetClient(ctx, r.Meta(), data.Namespace.ValueString())
	if err != nil {
		resp.Diagnostics.AddError(errutil.ClientConfigureErr(err))
		return
	}

	found, d := r.readFromVault(ctx, cli, &data)
	resp.Diagnostics.Append(d...)
	if resp.Diagnostics.HasError() {
		return
	}

	if !found {
		resp.Diagnostics.AddError("Resource not found", fmt.Sprintf("Transform transformation %q not found on mount %q", data.Name.ValueString(), data.Mount.ValueString()))
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

// readFromVault populates data from Vault. It returns false if the transformation does
// not exist (or on error, in which case the returned diag.Diagnostics contains the error).
func (r *TransformFPEImportedKeyResource) readFromVault(ctx context.Context, cli *vaultclient.Client, data *TransformFPEImportedKeyModel) (bool, diag.Diagnostics) {
	secretData, diags := readTransformation(ctx, cli, data.Mount.ValueString(), data.Name.ValueString(), typeFPE)
	if diags.HasError() || secretData == nil {
		return false, diags
	}

	diags.Append(data.setFromVault(ctx, secretData)...)

	data.Template = util.StringValueOrNull(secretData[consts.FieldTemplate])
	data.TweakSource = util.StringValueOrNull(secretData[consts.FieldTweakSource])
	data.MaxTweakLen = util.Int64ValueOrNull(secretData[consts.FieldMaxTweakLen])
	data.FPEAlgorithm = util.StringValueOrNull(secretData[consts.FieldFpeAlgorithm])

	return true, diags
}
