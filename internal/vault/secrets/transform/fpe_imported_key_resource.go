// TransformFPEImportedKeyResource manages a Vault Transform format-preserving encryption (FPE)
// transformation whose key material was imported (BYOK) instead of generated by Vault. The
// resource combines the initial import (/transformations/fpe/:name/import) with the ongoing
// transformation settings (/transformations/fpe/:name).
type TransformFPEImportedKeyResource struct {
	base.ResourceWithConfigure
}

// TransformFPEImportedKeyModel describes the Terraform resource data model.
type TransformFPEImportedKeyModel struct {
	ImportedKeyCommonModel

	Template     types.String `tfsdk:"template"`
	TweakSource  types.String `tfsdk:"tweak_source"`
	MaxTweakLen  types.Int64  `tfsdk:"max_tweak_len"`
	FPEAlgorithm types.String `tfsdk:"fpe_algorithm"`
}

func (r *TransformFPEImportedKeyResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_transform_transformation_fpe_imported_key"
}

func (r *TransformFPEImportedKeyResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	attrs := importedKeyCommonAttributes()

	// Vault cannot import a new key version into an existing FPE transformation, so
	// setting any new non-null version replaces it. Removing the version only clears state.
	attrs[consts.FieldCiphertextWOVersion] = schema.Int64Attribute{
		MarkdownDescription: "Version identifier for `ciphertext_wo`. Vault imports ciphertext on create; changing this value replaces the transformation. Removing it does not replace the resource. Required with `ciphertext_wo`.",
		Optional:            true,
		Validators: []validator.Int64{
			int64validator.AlsoRequires(path.MatchRoot(consts.FieldCiphertextWO)),
		},
		PlanModifiers: []planmodifier.Int64{
			int64planmodifier.RequiresReplaceIfConfigured(),
		},
	}
	attrs[consts.FieldTemplate] = schema.StringAttribute{
		MarkdownDescription: "The name of the template to use.",
		Required:            true,
	}
	attrs[consts.FieldTweakSource] = schema.StringAttribute{
		MarkdownDescription: "The source of the tweak value (`supplied`, `generated` or `internal`).",
		Optional:            true,
		Computed:            true,
		Validators: []validator.String{
			stringvalidator.OneOf("supplied", "generated", "internal"),
		},
		PlanModifiers: []planmodifier.String{
			stringplanmodifier.UseStateForUnknown(),
		},
	}
	attrs[consts.FieldMaxTweakLen] = schema.Int64Attribute{
		MarkdownDescription: "The maximum tweak length in bytes (0-32). If the value is 0, the tweak length can be any value from 0 to 32 bytes. Vault does not allow this field to be changed after creation, so changing it returns an error from Vault.",
		Optional:            true,
		Computed:            true,
		Validators: []validator.Int64{
			int64validator.Between(0, 32),
		},
		PlanModifiers: []planmodifier.Int64{
			int64planmodifier.UseStateForUnknown(),
		},
	}
	attrs[consts.FieldFpeAlgorithm] = schema.StringAttribute{
		MarkdownDescription: "The FPE algorithm used by this transformation. New transformations use `ff1`. `ff3-1` is deprecated as of Vault 2.2.0 and only appears on existing transformations; migrate its data to an `ff1` transformation with Vault's Rewrap endpoint. Set by Vault at creation time.",
		Computed:            true,
	}

	resp.Schema = schema.Schema{
		MarkdownDescription: "Creates a Vault Transform format-preserving encryption (FPE) transformation from externally generated key material (BYOK) and manages its settings. Requires Vault Enterprise.",
		Attributes:          attrs,
	}
	base.MustAddBaseSchema(&resp.Schema)
}

func (r *TransformFPEImportedKeyResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan TransformFPEImportedKeyModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// ciphertext_wo is write-only, so it is only available from config.
	var config TransformFPEImportedKeyModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &config)...)
	if resp.Diagnostics.HasError() {
		return
	}

	cli, err := client.GetClient(ctx, r.Meta(), plan.Namespace.ValueString())
	if err != nil {
		resp.Diagnostics.AddError(errutil.ClientConfigureErr(err))
		return
	}

	if !provider.IsEnterpriseSupported(r.Meta()) {
		resp.Diagnostics.AddError("Unsupported Vault edition", "The Transform secrets engine requires Vault Enterprise.")
		return
	}

	body, d := plan.importBody(ctx, &config.ImportedKeyCommonModel)
	resp.Diagnostics.Append(d...)
	if resp.Diagnostics.HasError() {
		return
	}
	body["template"] = plan.Template.ValueString()
	if !plan.TweakSource.IsNull() && !plan.TweakSource.IsUnknown() {
		body["tweak_source"] = plan.TweakSource.ValueString()
	}
	if !plan.MaxTweakLen.IsNull() && !plan.MaxTweakLen.IsUnknown() {
		body["max_tweak_len"] = plan.MaxTweakLen.ValueInt64()
	}

	mount := plan.Mount.ValueString()
	name := plan.Name.ValueString()

	if _, err := cli.Logical().WriteWithContext(ctx, importPath(mount, typeFPE, name), body); err != nil {
		resp.Diagnostics.AddError(errutil.VaultCreateErr(err))
		return
	}

	// deletion_allowed is not accepted by /import, only by the update endpoint, so it is applied
	// with a second write.
	//
	// The transformation exists in Vault once /import succeeds. Record errors from this write,
	// but don't immediately return so the transformation imported earlier stays tracked.
	if !plan.DeletionAllowed.IsNull() && !plan.DeletionAllowed.IsUnknown() {
		b := map[string]any{"deletion_allowed": plan.DeletionAllowed.ValueBool()}
		if _, err := cli.Logical().WriteWithContext(ctx, typedPath(mount, typeFPE, name), b); err != nil {
			resp.Diagnostics.AddError(errutil.VaultCreateErr(err))
		}
	}

	found, d := r.readFromVault(ctx, cli, &plan)
	resp.Diagnostics.Append(d...)
	if d.HasError() {
		return
	}
	if !found {
		resp.Diagnostics.AddError(errutil.VaultReadResponseNil())
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *TransformFPEImportedKeyResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state TransformFPEImportedKeyModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	cli, err := client.GetClient(ctx, r.Meta(), state.Namespace.ValueString())
	if err != nil {
		resp.Diagnostics.AddError(errutil.ClientConfigureErr(err))
		return
	}

	found, d := r.readFromVault(ctx, cli, &state)
	resp.Diagnostics.Append(d...)
	if resp.Diagnostics.HasError() {
		return
	}

	if !found {
		tflog.Warn(ctx, "Transform transformation not found, removing from state")
		resp.State.RemoveResource(ctx)
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *TransformFPEImportedKeyResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan TransformFPEImportedKeyModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	var state TransformFPEImportedKeyModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	cli, err := client.GetClient(ctx, r.Meta(), plan.Namespace.ValueString())
	if err != nil {
		resp.Diagnostics.AddError(errutil.ClientConfigureErr(err))
		return
	}

	mount := plan.Mount.ValueString()
	name := plan.Name.ValueString()

	body, d := plan.updateBody(ctx)
	resp.Diagnostics.Append(d...)
	if resp.Diagnostics.HasError() {
		return
	}
	if !plan.TweakSource.IsNull() && !plan.TweakSource.IsUnknown() {
		body["tweak_source"] = plan.TweakSource.ValueString()
	}
	body["template"] = plan.Template.ValueString()
	// Vault rejects max_tweak_len on any update, even with an unchanged value, so it is only sent
	// when the configured value differs from state. Vault then returns its own error for it.
	if !plan.MaxTweakLen.IsNull() && !plan.MaxTweakLen.IsUnknown() && !plan.MaxTweakLen.Equal(state.MaxTweakLen) {
		body["max_tweak_len"] = plan.MaxTweakLen.ValueInt64()
	}

	if len(body) > 0 {
		if _, err := cli.Logical().WriteWithContext(ctx, typedPath(mount, typeFPE, name), body); err != nil {
			resp.Diagnostics.AddError(errutil.VaultUpdateErr(err))
			return
		}
	}

	found, d := r.readFromVault(ctx, cli, &plan)
	resp.Diagnostics.Append(d...)
	if d.HasError() {
		return
	}
	if !found {
		resp.Diagnostics.AddError(errutil.VaultReadResponseNil())
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

